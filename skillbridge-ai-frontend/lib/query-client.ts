import { QueryClient } from "@tanstack/react-query";

/**
 * Single shared QueryClient for backend requests and local prototype fixtures.
 */
export function makeQueryClient() {
  return new QueryClient({
    defaultOptions: {
      queries: {
        staleTime: 60 * 1000,
        refetchOnWindowFocus: false,
        retry: 1,
      },
      mutations: {
        retry: 0,
      },
    },
  });
}
